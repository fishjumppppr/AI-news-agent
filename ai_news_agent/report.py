def fallback_report(items: List[NewsItem], report_date: str, error: Exception) -> str:
    lines = [
        f"# AI / Agent 前沿资讯日报 - {report_date}",
        "",
        "## 生成状态",
        "",
        f"LiteLLM 总结失败：`{error}`",
        "",
        "下面是已抓取并过滤后的候选资讯，方便排查或手动阅读。",
        "",
        "## 候选来源",
        "",
    ]
    for item in items:
        published = item.published_at.isoformat() if item.published_at else "unknown"
        lines.extend(
            [
                f"- [{item.title}]({item.url})",
                f"  - 来源：{item.source}",
                f"  - 发布时间：{published}",
                f"  - 摘要：{item.summary[:300]}",
            ]
        )
    return "\n".join(lines).strip() + "\n"


