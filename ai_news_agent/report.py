def write_report(report_dir: Path, report_date: str, content: str) -> Path:
    report_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().isoformat(timespec="seconds")
    markdown_path = report_dir / f"{report_date}.md"
    markdown_path.write_text(f"{content.rstrip()}\n\n<!-- generated_at: {stamp} -->\n", encoding="utf-8")

    path = report_dir / f"{report_date}.html"
    path.write_text(render_html(content, report_date, stamp), encoding="utf-8")
    return path
